  '',
  '## FFmpeg and x264 (separate executable)',
  '',
  'The installers include an `ffmpeg` executable that the app starts as an external program (it is not linked into the app).',
  'On macOS it is built from unmodified upstream sources with `tools/ffmpeg/build-macos.sh`: FFmpeg 6.1.1 and x264 (commit',
  '`b35605ace3ddf7c1a5d67a2eb553f034aef41d55`), licensed under the **GNU General Public License v2 or later**, with libx264 only',
  'and no nonfree code. The license texts (`COPYING.GPLv2`, `COPYING.GPLv3`) and `SOURCE.txt` are installed next to the executable',
  '(`resources/ffmpeg/`).',
  '',
  '- FFmpeg source: https://ffmpeg.org/releases/ffmpeg-6.1.1.tar.xz (SHA-256 `8684f4b00f94b85461884c3719382f1261f0d9eb3d59640a1f4ac0873616f968`)',
  '- x264 source: https://code.videolan.org/videolan/x264 at the commit above',
  '- To rebuild the exact binary: `tools/ffmpeg/build-macos.sh`',
  '',
  'The Windows installer ships a pinned third-party build instead: FFmpeg 6.1.1 "essentials" from www.gyan.dev (GNU GPL v3,',
  'no nonfree code), fetched by `tools/ffmpeg/fetch-windows.sh` from a fixed release with SHA-256 checks. It statically links',
  'about 35 libraries (including the GPL libraries x264, x265 and xvid). Its license text, build notes and a `SOURCE.txt` are',
  'installed next to it. **Known gap:** the builder publishes only the FFmpeg source commit; the corresponding source of the',
  'statically linked libraries is not provided by us yet (see `tools/ffmpeg/README.md`).',
  '',
  '## Electron and Chromium',
  '',
  'The app runs on Electron (MIT) which includes Chromium and other components. Their license texts are installed with the app',
  'as `LICENSE.electron.txt` and `LICENSES.chromium.html`.',
