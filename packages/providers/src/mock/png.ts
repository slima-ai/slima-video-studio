export const GLYPH_WIDTH = 5
export const GLYPH_HEIGHT = 7

/** 把任意字串轉成字型畫得出來的大寫 ASCII（其他字元變成 `?`）。 */
export function toLabelText(text: string): string {
  return text
    .toUpperCase()
    .split('')
    .map((ch) => (ch in FONT ? ch : '?'))
    .join('')
}

export interface Canvas {
  width: number
  height: number
  rgb: Uint8Array
}

export function createCanvas(
  width: number,
  height: number,
  color: readonly [number, number, number],
): Canvas {
  const rgb = new Uint8Array(width * height * 3)
  for (let i = 0; i < width * height; i++) {
    rgb[i * 3] = color[0]
    rgb[i * 3 + 1] = color[1]
    rgb[i * 3 + 2] = color[2]
  }
  return { width, height, rgb }
}

/** 在畫布上畫一行字（scale 倍放大）。超出畫布的部分會被裁掉。 */
export function drawText(
  canvas: Canvas,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: readonly [number, number, number],
): void {
  let cursor = x
  for (const ch of toLabelText(text)) {
    const rows = FONT[ch] ?? FONT['?'] ?? []
    rows.forEach((bits, row) => {
      for (let col = 0; col < GLYPH_WIDTH; col++) {
        if ((bits >> (GLYPH_WIDTH - 1 - col)) & 1)
          fillRect(canvas, cursor + col * scale, y + row * scale, scale, scale, color)
      }
    })
    cursor += (GLYPH_WIDTH + 1) * scale
  }
}

function fillRect(
  canvas: Canvas,
  x: number,
  y: number,
  w: number,
  h: number,
  color: readonly [number, number, number],
): void {
  for (let yy = Math.max(0, y); yy < Math.min(canvas.height, y + h); yy++) {
    for (let xx = Math.max(0, x); xx < Math.min(canvas.width, x + w); xx++) {
      const i = (yy * canvas.width + xx) * 3
      canvas.rgb[i] = color[0]
      canvas.rgb[i + 1] = color[1]
      canvas.rgb[i + 2] = color[2]
    }
  }
}
